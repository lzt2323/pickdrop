import { readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
const root = new URL('../', import.meta.url);
const source = new URL('apps/desktop/public/assets/animals/', root);
// Native SvgXml has no CSS cascade. Flatten the authored CSS and convert OKLCH
// to sRGB before bundling, while preserving all geometry and the original viewBox.
function srgb(value) {
  const match = /^oklch\(([\d.]+)%\s+([\d.]+)\s+([\d.]+)\)$/.exec(value);
  if (!match) return value;
  const L = Number(match[1]) / 100, C = Number(match[2]), h = Number(match[3]) * Math.PI / 180;
  const a = C * Math.cos(h), b = C * Math.sin(h);
  const l = (L + .3963377774*a + .2158037573*b)**3;
  const m = (L - .1055613458*a - .0638541728*b)**3;
  const s = (L - .0894841775*a - 1.291485548*b)**3;
  const channels = [4.0767416621*l-3.3077115913*m+.2309699292*s,-1.2684380046*l+2.6097574011*m-.3413193965*s,-.0041960863*l-.7034186147*m+1.707614701*s];
  return '#'+channels.map(c=>Math.round(Math.max(0,Math.min(1,c<=.0031308?12.92*c:1.055*c**(1/2.4)-.055))*255).toString(16).padStart(2,'0')).join('');
}
const drawings = {};
for (const name of (await readdir(source)).filter(name=>name.endsWith('.svg')).sort()) {
 let svg=await readFile(new URL(name,source),'utf8');
 const css=svg.match(/<style>([\s\S]*?)<\/style>/)?.[1]||'';
 const variables=Object.fromEntries([...css.matchAll(/(--[\w-]+):([^;}]+)/g)].map(([,key,value])=>[key,srgb(value)]));
 const classes=Object.fromEntries([...css.matchAll(/\.([\w-]+)\{([^}]+)\}/g)].map(([,key,value])=>[key,value]));
 svg=svg.replace(/<style>[\s\S]*?<\/style>/g,'').replace(/\s(?:role|aria-label)="[^"]*"/g,'');
 svg=svg.replace(/class="([^"]+)"/g,(_,list)=>{
  const attributes={};
  for(const key of list.split(/\s+/))for(const decl of (classes[key]||'').split(';')){
   const colon=decl.indexOf(':');if(colon<0)continue;
   attributes[decl.slice(0,colon)]=decl.slice(colon+1).replace(/var\((--[\w-]+)\)/g,(_,v)=>variables[v]);
  }
  return Object.entries(attributes).map(([k,v])=>`${k}="${v}"`).join(' ');
 });
 if (/class=|<style|var\(|oklch\(/.test(svg)) throw Error(`Unflattened native SVG: ${name}`);
 drawings[path.basename(name,'.svg')]=svg;
}
await writeFile(new URL('apps/mobile/src/paw-animals.ts',root),`// Generated by scripts/generate-mobile-paw-animals.js; native-compatible SVG attributes.\nconst drawings: Record<string, string> = ${JSON.stringify(drawings,null,2)};\nexport const pawAnimalSvg = (id: string) => drawings[id] || drawings.cat;\n`);
console.log(`Generated ${Object.keys(drawings).length} native-compatible animals.`);
